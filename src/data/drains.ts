export const hotspots: Hotspot[] = drainSegments
  .filter((d) => d.riskLevel === 'critical' || d.riskLevel === 'high')
  .map((d) => ({
    id: `HS-${d.id}`,
    name: d.name,
    lat: d.path[0].lat,
    lng: d.path[0].lng,
    riskLevel: d.riskLevel,
    drainId: d.id,
  }))

